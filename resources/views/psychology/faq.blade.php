                <div class="faq-container">
                    <article class="faq-item">
                        <button class="faq-question">
                            <span>Can psychologists predict who will become a serial killer?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                No. Psychology can identify risk factors and behavioural
                                patterns, but no scientific method can accurately predict
                                whether a specific individual will become a serial offender.
                            </p>
                        </div>
                    </article>

                    <article class="faq-item">
                        <button class="faq-question">
                            <span>Is every serial killer a psychopath?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                No. While psychopathic traits appear in some serial offenders,
                                others do not meet the criteria associated with psychopathy.
                                Motivation and personality vary considerably between cases.
                            </p>
                        </div>
                    </article>

                    <article class="faq-item">
                        <button class="faq-question">
                            <span>Does childhood trauma create violent offenders?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                No. Trauma may increase vulnerability to certain behavioural
                                difficulties, but most people who experience childhood trauma
                                never commit violent crimes.
                            </p>
                        </div>
                    </article>
                    <article class="faq-item">
                        <button class="faq-question">
                            <span>Can criminal profiling identify a suspect?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                No. Profiling helps investigators understand behavioural patterns and
                                narrow investigative strategies, but it cannot identify a specific
                                individual without supporting evidence.
                            </p>
                        </div>
                    </article>

                    <article class="faq-item">
                        <button class="faq-question">
                            <span>Are people with mental illnesses more likely to be violent?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                No. Most people living with mental illnesses never commit violent
                                offences. Research shows they are more likely to become victims of
                                crime than perpetrators.
                            </p>
                        </div>
                    </article>

                    <article class="faq-item">
                        <button class="faq-question">
                            <span>What is the difference between a motive and a motive for profiling?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                A motive explains why someone committed a crime, while behavioural
                                analysis examines how the crime was committed. Investigators often
                                understand behaviour long before a clear motive is established.
                            </p>
                        </div>
                    </article>

                    <article class="faq-item">
                        <button class="faq-question">
                            <span>Can body language reveal if someone is lying?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                No single gesture reliably indicates deception. Professionals rely on
                                context, evidence, and behavioural changes rather than isolated body
                                language cues.
                            </p>
                        </div>
                    </article>

                    <article class="faq-item">
                        <button class="faq-question">
                            <span>Do all criminals repeat the same behaviour?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                Not necessarily. Offenders often adapt their methods over time as they
                                gain experience or attempt to avoid detection. Some behavioural
                                patterns remain consistent, while others change.
                            </p>
                        </div>
                    </article>

                    <article class="faq-item">
                        <button class="faq-question">
                            <span>Why is victimology important?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                Victimology helps investigators understand the impact of crime,
                                improve support services, identify risk factors, and ensure victims
                                remain central throughout the investigative process.
                            </p>
                        </div>
                    </article>

                    <article class="faq-item">
                        <button class="faq-question">
                            <span>Can psychology explain every crime?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                No. Psychology provides valuable insight into behaviour, but criminal
                                actions are influenced by many interacting biological,
                                psychological, social, and situational factors.
                            </p>
                        </div>
                    </article>

                    <article class="faq-item">
                        <button class="faq-question">
                            <span>Is criminal psychology the same as forensic psychology?</span>
                            <span class="faq-icon">+</span>
                        </button>

                        <div class="faq-answer">
                            <p>
                                Not exactly. Criminal psychology focuses on understanding offender
                                behaviour, while forensic psychology applies psychological knowledge
                                within the legal and criminal justice systems, including assessments,
                                treatment, and expert testimony.
                            </p>
                        </div>
                    </article>
                </div>
