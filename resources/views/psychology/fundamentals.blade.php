            <!-- ====== NATURE VS NURTURE ====== -->
            <section id="nature" class="psychology-section">
                <div class="section-heading">
                    <span class="section-tag">Development</span>
                    <h2>Nature vs Nurture</h2>
                </div>

                <div class="split-layout">
                    <div class="split-column">
                        <h3>Nature</h3>

                        <p style="margin-bottom:15px">
                            Nature refers to the biological factors that influence behaviour,
                            including genetics, inherited traits, prenatal development and
                            neurological differences. Research suggests that certain biological
                            characteristics may contribute to aggression, impulsivity or
                            reduced emotional responsiveness, but they do not create criminals
                            on their own.
                        </p>

                        <p>
                            Modern neuroscience continues to explore how brain structure,
                            hormones and genetics interact with experience throughout life.
                        </p>
                    </div>

                    <div class="split-divider"></div>

                    <div class="split-column">
                        <h3>Nurture</h3>

                        <p style="margin-bottom:15px">
                            Nurture describes everything experienced after birth. Parenting,
                            education, friendships, trauma, neglect, abuse, poverty,
                            community, culture and opportunity all shape personality and
                            behaviour.
                        </p>

                        <p>
                            Most psychologists agree that neither nature nor nurture acts
                            alone. Instead, criminal behaviour develops through the continuous
                            interaction between biological predispositions and environmental
                            experiences.
                        </p>
                    </div>
                </div>

                <div class="quote-card">
                    <blockquote>
                        "Genes load the gun, personality and psychology aim it, and life experiences pull the trigger."
                    </blockquote>

                    <span>
                        A simplified metaphor often used to illustrate the interaction between
                        biology and environment. It should not be interpreted literally.
                    </span>
                </div>
            </section>

            <!-- ====== BEHAVIOURAL DEVELOPMENT TIMELINE ====== -->
            <section id="timeline" class="psychology-section">
                <div class="section-heading">
                    <span class="section-tag">Behavioural Development</span>
                    <h2>How Violent Behaviour Can Develop</h2>
                </div>

                <div class="psychology-card timeline-introduction">
                    <p>
                        There is no universal path that leads to violent crime. Every person's
                        life is different, and no timeline can predict who will become an
                        offender. The illustration below represents a simplified developmental
                        model used to explain how multiple biological, psychological and
                        environmental influences may interact over many years. At any stage,
                        protective factors such as supportive relationships, therapy,
                        education, positive role models and timely intervention can alter an individual's direction.
                    </p>
                </div>

                <div class="development-timeline">
                    <div class="timeline-line"></div>

                    <article class="timeline-item">
                        <div class="timeline-marker">01</div>

                        <div class="timeline-content">
                            <h3>Early Childhood</h3>

                            <p>
                                The earliest years of life play an important role in emotional
                                development. Secure attachment, consistent care and positive
                                social interaction help children develop empathy, trust and
                                emotional regulation. Chronic neglect, instability or severe
                                abuse may interfere with these developmental processes,
                                although many children exposed to adversity grow into healthy, non-violent adults.
                            </p>
                        </div>
                    </article>

                    <article class="timeline-item">
                        <div class="timeline-marker">02</div>

                        <div class="timeline-content">
                            <h3>Trauma & Adverse Experiences</h3>

                            <p>
                                Repeated exposure to violence, emotional abuse, sexual abuse,
                                bullying or household dysfunction can influence the way an
                                individual perceives relationships, conflict and personal
                                safety. These experiences may contribute to anxiety,
                                hypervigilance, emotional detachment or difficulties forming
                                healthy attachments, but they are never direct causes of criminal behaviour.
                            </p>
                        </div>
                    </article>

                    <article class="timeline-item">
                        <div class="timeline-marker">03</div>

                        <div class="timeline-content">
                            <h3>Personality Development</h3>

                            <p>
                                During adolescence, personality traits become increasingly
                                stable. Impulsivity, sensation seeking, emotional regulation,
                                empathy and social learning all continue developing. Positive
                                friendships, education and supportive adults often act as
                                protective factors during this period.
                            </p>
                        </div>
                    </article>

                    <article class="timeline-item">
                        <div class="timeline-marker">04</div>

                        <div class="timeline-content">
                            <h3>Cognitive Distortions</h3>

                            <p>
                                Some offenders develop distorted ways of thinking that justify
                                aggression or shift responsibility onto others. These beliefs
                                may include blaming victims, minimizing harm, believing that
                                violence solves problems or viewing other people as objects
                                rather than individuals.
                            </p>
                        </div>
                    </article>

                    <article class="timeline-item">
                        <div class="timeline-marker">05</div>

                        <div class="timeline-content">
                            <h3>Escalation</h3>

                            <p>
                                Behaviour sometimes progresses gradually. Minor rule-breaking
                                may develop into repeated offending when reinforced by success,
                                opportunity or lack of consequences. Escalation is not
                                inevitable, and intervention at any point can interrupt this process.
                            </p>
                        </div>
                    </article>
                </div>
            </section>

            <!-- ====== THE HUMAN BRAIN ====== -->
            <section id="brain" class="psychology-section">
                <div class="section-heading">
                    <span class="section-tag">Neuroscience</span>
                    <h2>The Brain & Criminal Behaviour</h2>
                </div>

                <div class="brain-information">
                    <p>
                        Advances in neuroscience have improved our understanding of how
                        different brain regions contribute to behaviour. While no "criminal
                        brain" exists, researchers have identified areas involved in
                        emotional processing, impulse control, empathy and decision making.
                    </p>

                    <p>
                        Brain structure alone cannot explain violent crime. Most people
                        with neurological differences never commit offences, highlighting
                        the importance of environmental influences and individual choice.
                    </p>
                </div>

                <div class="brain-region-grid">
                    <article class="brain-region">
                        <h3>Prefrontal Cortex</h3>

                        <p>
                            Responsible for planning, judgement, impulse control and weighing
                            consequences before making decisions.
                        </p>
                    </article>

                    <article class="brain-region">
                        <h3>Amygdala</h3>

                        <p>
                            Plays a central role in processing fear, emotional learning and
                            recognising emotional expressions in other people.
                        </p>
                    </article>

                    <article class="brain-region">
                        <h3>Hippocampus</h3>

                        <p>Supports memory formation and helps individuals learn from previous experiences.</p>
                    </article>

                    <article class="brain-region">
                        <h3>Anterior Cingulate Cortex</h3>

                        <p>
                            Involved in emotional regulation, empathy, error detection and
                            conflict monitoring during complex decision making.
                        </p>
                    </article>
                </div>
            </section>

