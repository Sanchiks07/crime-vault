            <!-- ====== HISTORY OF CRIMINAL PSYCHOLOGY ====== -->
            <section class="psychology-section" id="history">
                <div class="section-heading">
                    <span class="section-tag">Historical Development</span>
                    <h2>History of Criminal Psychology</h2><br>
                    <p class="psychology-card" style="margin-top:20px">
                        Criminal psychology did not appear overnight. It evolved through centuries of changing beliefs,
                        scientific discoveries, and countless mistakes. Every generation believed it had finally
                        discovered the answer to criminal behavior, only for later evidence to challenge those ideas.
                    </p>
                </div>

                <div class="timeline-container">
                    <div class="timeline-item">
                        <div class="timeline-year">1700s</div>
                        <div class="timeline-content">
                            <h3>Punishment Before Understanding</h3>

                            <p>
                                Crime was commonly viewed as evidence of evil, sin, or moral corruption.
                                Little effort was made to understand motivation.
                                Justice focused on punishment rather than prevention.
                            </p>
                        </div>
                    </div>

                    <div class="timeline-item">
                        <div class="timeline-year">1800s</div>
                        <div class="timeline-content">
                            <h3>The Search for the "Born Criminal"</h3>

                            <p>
                                Early researchers attempted to connect criminality to physical appearance.
                                Measurements of skulls, faces, and body proportions were believed to reveal
                                dangerous individuals.
                            </p>

                            <p>
                                Modern science has thoroughly rejected these theories.
                                They are remembered today as examples of how bias can disguise itself as science.
                            </p>
                        </div>
                    </div>

                    <div class="timeline-item">
                        <div class="timeline-year">1900s</div>
                        <div class="timeline-content">
                            <h3>The Rise of Psychology</h3>

                            <p>
                                Researchers gradually shifted away from appearance and toward behavior,
                                personality, childhood experiences, trauma, learning, and mental processes.
                                Interviews, observations, and psychological testing became increasingly important.
                            </p>
                        </div>
                    </div>

                    <div class="timeline-item">
                        <div class="timeline-year">Modern Day</div>
                        <div class="timeline-content">
                            <h3>An Interdisciplinary Field</h3>

                            <p>
                                Criminal psychology now combines neuroscience, behavioral science,
                                forensic psychology, sociology, criminology, statistics,
                                and investigative practice.
                            </p>

                            <p>
                                Rather than searching for one explanation,
                                professionals recognize that criminal behavior usually develops through
                                multiple interacting influences.
                            </p>
                        </div>
                    </div>
                </div>
