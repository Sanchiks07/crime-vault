            <!-- ORGANIZED vs DISORGANIZED OFFENDERS -->
            <!-- ===================================== -->
            <section class="psychology-section">
                <div class="section-heading">
                    <span class="section-tag">Behavioural Classification</span>
                    <h2>Organized & Disorganized Offenders</h2>
                </div>

                <div class="comparison-large">
                    <article class="comparison-panel">
                        <h3>Organized Behaviour</h3>

                        <p>
                            Organized offenders generally plan their crimes, prepare for
                            possible complications and attempt to reduce the likelihood of
                            identification. Their crimes often reflect patience, control and preparation.
                        </p>

                        <ul>
                            <li>Crime planned in advance.</li>
                            <li>Victim intentionally selected.</li>
                            <li>Weapon brought to the scene.</li>
                            <li>Evidence removed or concealed.</li>
                            <li>Higher awareness of forensic evidence.</li>
                        </ul>
                    </article>

                    <article class="comparison-panel">
                        <h3>Disorganized Behaviour</h3>

                        <p>
                            Disorganized offenders often act impulsively, leaving behind more
                            evidence and displaying less planning. Their crimes may appear
                            chaotic and emotionally driven.
                        </p>

                        <ul>
                            <li>Little or no planning.</li>
                            <li>Random victim selection.</li>
                            <li>Weapon found at scene.</li>
                            <li>Evidence frequently left behind.</li>
                            <li>Higher emotional reactivity.</li>
                        </ul>
                    </article>
                </div>

                <div class="myth-warning">
                    <h3>Modern Perspective</h3>

                    <p>
                        Today's researchers recognise that very few offenders fit perfectly
                        into either category. Most exhibit a combination of organized and
                        disorganized behaviours depending on experience, circumstances and the
                        specific offence.
                    </p>
                </div>
