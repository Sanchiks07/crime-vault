            <section class="psychology-section">
                <div class="section-heading">
                    <span class="section-tag">Behavioural Analysis</span>
                    <h2>Modus Operandi vs Signature</h2>
                </div>

                <div class="comparison-large">
                    <article class="comparison-panel">
                        <h3>Modus Operandi (MO)</h3>

                        <p>
                            A Modus Operandi refers to the practical methods an offender uses
                            to successfully commit a crime and avoid detection. Because
                            offenders learn from experience, an MO can change over time.
                        </p>

                        <ul>
                            <li>Planning the crime.</li>
                            <li>Selecting a weapon.</li>
                            <li>Choosing a victim.</li>
                            <li>Escaping the scene.</li>
                            <li>Destroying evidence.</li>
                        </ul>
                    </article>

                    <article class="comparison-panel">
                        <h3>Signature Behaviour</h3>

                        <p>
                            A signature reflects psychological or emotional needs rather than
                            practical necessity. These behaviours often remain relatively
                            consistent because they fulfil an internal fantasy or emotional
                            purpose.
                        </p>

                        <ul>
                            <li>Leaving symbolic objects.</li>
                            <li>Specific posing of victims.</li>
                            <li>Unique rituals.</li>
                            <li>Communication with investigators.</li>
                            <li>Repeated symbolic behaviours.</li>
                        </ul>
                    </article>
                </div>

                <div class="psychology-card">
                    <p>
                        Understanding the distinction between MO and signature behaviour helps
                        investigators connect related offences and better understand offender
                        behaviour. While an offender may alter practical methods to avoid
                        capture, deeply personal psychological rituals often remain remarkably consistent.
                    </p>
                </div>
            </section>

