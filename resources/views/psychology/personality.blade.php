            <!-- ===================================== -->
            <section class="psychology-section">
                <div class="section-heading">
                    <span class="section-tag">Clinical Psychology</span>
                    <h2>Personality Disorders & Crime</h2>
                </div>

                <div class="psychology-card">
                    <p>
                        Personality disorders describe long-lasting patterns of thinking,
                        feeling and behaving that differ significantly from cultural
                        expectations and often interfere with relationships, work and daily
                        functioning. While some personality disorders appear more frequently
                        within correctional settings, having a personality disorder does not
                        make someone dangerous or violent.
                    </p>
                </div>

                <div class="psychology-grid disorder-grid">
                    <article class="disorder-card">
                        <h3>Antisocial Personality Disorder</h3>

                        <p>
                            Characterised by persistent disregard for the rights of others,
                            repeated rule-breaking, deception, impulsivity and a lack of
                            remorse. ASPD is the personality disorder most commonly discussed
                            in forensic psychology.
                        </p>
                    </article>

                    <article class="disorder-card">
                        <h3>Narcissistic Personality Disorder</h3>

                        <p>
                            Individuals may display grandiosity, an excessive need for
                            admiration and difficulty accepting criticism. Contrary to popular
                            belief, narcissism alone does not predict violent behaviour.
                        </p>
                    </article>

                    <article class="disorder-card">
                        <h3>Borderline Personality Disorder</h3>

                        <p>
                            Marked by emotional instability, fear of abandonment and rapidly
                            changing relationships. People with BPD are statistically far more
                            likely to harm themselves than others.
                        </p>
                    </article>

                    <article class="disorder-card">
                        <h3>Paranoid Personality Disorder</h3>

                        <p>
                            Characterised by persistent distrust and suspicion of others.
                            Individuals often interpret harmless situations as threatening,
                            although violence is not an inevitable outcome.
                        </p>
                    </article>
                </div>
            </section>

