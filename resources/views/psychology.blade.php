            <!-- ===================================== -->
            <section id="profiling" class="psychology-section">
                <div class="section-heading">
                    <span class="section-tag">Investigation</span>
                    <h2>Criminal Profiling</h2>
                </div>

                <div class="psychology-card">
                    <p>
                        Criminal profiling is one of the most misunderstood areas of forensic
                        psychology. Popular television often presents profilers as individuals
                        capable of identifying an unknown offender after only a brief glance at
                        a crime scene. In reality, profiling is an investigative tool rather
                        than a method of solving crimes on its own.
                    </p>

                    <p>
                        Profilers examine behavioural evidence left behind by offenders. They
                        study how crimes were committed, how victims were selected, whether the
                        offender demonstrated planning or impulsivity, and whether multiple
                        crimes may have been committed by the same individual. Their findings
                        help investigators prioritise leads, understand offender behaviour and
                        narrow investigative strategies.
                    </p>
                </div>

                <div class="psychology-grid">
                    <article class="psychology-info-card">
                        <h3>Behavioural Evidence</h3>

                        <p>
                            Every crime scene tells a behavioural story. The level of planning,
                            violence, victim interaction and attempts to hide evidence can
                            reveal valuable information about the offender's decisions before,
                            during and after the offence.
                        </p>
                    </article>

                    <article class="psychology-info-card">
                        <h3>Victimology</h3>

                        <p>
                            Investigators carefully examine the victim's lifestyle,
                            relationships, occupation and daily routines. Understanding why a
                            particular victim was chosen often provides insight into offender
                            motivation.
                        </p>
                    </article>

                    <article class="psychology-info-card">
                        <h3>Geographic Profiling</h3>

                        <p>
                            The locations of multiple offences may reveal travel patterns,
                            comfort zones and areas familiar to the offender. Geographic
                            profiling combines behavioural science with spatial analysis to
                            support investigations.
                        </p>
                    </article>

                    <article class="psychology-info-card">
                        <h3>Linkage Analysis</h3>

                        <p>
                            Detectives compare crime scene characteristics to determine whether
                            several offences were likely committed by the same individual or group.
                        </p>
                    </article>
                </div>
            </section>

