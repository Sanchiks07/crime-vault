            <!-- PSYCHOPATHY -->
            <!-- ===================================== -->
            <section id="psychopathy" class="psychology-section">
                <div class="section-heading">
                    <span class="section-tag">Personality</span>
                    <h2>Psychopathy & Sociopathy</h2>
                </div>

                <div class="psychology-card">
                    <p>
                        Few psychological terms are as misunderstood as <strong>psychopath</strong>
                        and <strong>sociopath</strong>. They are frequently used in films,
                        television and news reports to describe anyone who commits a violent
                        crime, but modern psychology uses these concepts far more carefully.
                    </p>

                    <p>
                        Interestingly, <strong>"psychopath"</strong> is not an official
                        clinical diagnosis listed in the Diagnostic and Statistical Manual of
                        Mental Disorders (DSM-5). Instead, many individuals described as
                        psychopaths meet the diagnostic criteria for
                        <strong>Antisocial Personality Disorder (ASPD)</strong>, while also
                        displaying a unique collection of personality traits such as shallow
                        emotions, manipulation and a lack of remorse.
                    </p>

                    <p>
                        The word <strong>"sociopath"</strong> is even less formally defined
                        and is often used to describe individuals whose antisocial behaviour
                        appears to be influenced more heavily by environmental factors than by
                        biological predisposition. Although both terms are commonly discussed,
                        psychologists generally focus on measurable personality traits rather
                        than labels.
                    </p>
                </div>

                <div class="comparison-grid">
                    <article class="comparison-card">
                        <div class="comparison-header">
                            <span class="comparison-number">01</span>
                            <h3>Psychopathy</h3>
                        </div>

                        <ul>
                            <li>Often calm under pressure.</li>
                            <li>Highly manipulative and deceptive.</li>
                            <li>Superficially charming.</li>
                            <li>Limited empathy and remorse.</li>
                            <li>Behaviour is often carefully planned.</li>
                            <li>May successfully blend into society.</li>
                        </ul>
                    </article>

                    <article class="comparison-card">
                        <div class="comparison-header">
                            <span class="comparison-number">02</span>
                            <h3>Sociopathy</h3>
                        </div>

                        <ul>
                            <li>More emotionally reactive.</li>
                            <li>Often impulsive.</li>
                            <li>Difficulty maintaining relationships.</li>
                            <li>May experience guilt toward certain people.</li>
                            <li>Behaviour is frequently disorganized.</li>
                            <li>Often struggles with long-term planning.</li>
                        </ul>
                    </article>
                </div>

                <div class="myth-warning">
                    <h3>Important Reminder</h3>

                    <p>
                        Most people diagnosed with personality disorders never become violent
                        offenders. Likewise, many violent offenders do not meet the criteria
                        for psychopathy. Human behaviour is far too complex to be explained by
                        a single diagnosis or personality trait.
                    </p>
                </div>
            </section>

