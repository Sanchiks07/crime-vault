            <!-- SERIAL KILLER TYPOLOGIES -->
            <!-- ===================================== -->
            <section class="psychology-section">
                <div class="section-heading">
                    <span class="section-tag">Motivation</span>
                    <h2>Common Serial Killer Typologies</h2>
                </div>

                <div class="psychology-card">
                    <p>
                        Criminologists have proposed several systems for classifying serial
                        offenders based on their primary motivations. These categories are not
                        strict scientific diagnoses, and many offenders display characteristics
                        that overlap multiple groups. Nevertheless, they provide a useful
                        framework for understanding recurring behavioural patterns observed in
                        criminal investigations.
                    </p>
                </div>

                <div class="psychology-grid typology-grid">
                    <article class="typology-card">
                        <span class="typology-number">I</span>
                        <h3>Visionary</h3>

                        <p>
                            Claims to be directed by hallucinations, voices or imagined
                            supernatural forces. Genuine psychotic disorders are relatively
                            uncommon among serial offenders.
                        </p>
                    </article>

                    <article class="typology-card">
                        <span class="typology-number">II</span>
                        <h3>Mission-Oriented</h3>

                        <p>
                            Believes a specific group of people should be eliminated because
                            they are viewed as undesirable or harmful to society.
                        </p>
                    </article>

                    <article class="typology-card">
                        <span class="typology-number">III</span>
                        <h3>Hedonistic</h3>

                        <p>
                            Motivated primarily by pleasure. This may include thrill seeking,
                            sexual gratification or financial gain depending on the individual.
                        </p>
                    </article>

                    <article class="typology-card">
                        <span class="typology-number">IV</span>
                        <h3>Power / Control</h3>

                        <p>
                            Seeks domination over victims. The offender's primary motivation
                            is often psychological control rather than material reward.
                        </p>
                    </article>
                </div>
            </section>

